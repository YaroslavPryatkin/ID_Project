package com.postgres_gui.database;

public class FunctionParameter {
    private String name;
    private String type;

    public FunctionParameter(String name, String type) {
        this.name = name;
        this.type = type;
    }

    public String getName() {
        return name;
    }

    public String getType() {
        return type;
    }

    @Override
    public String toString() {
        return name + " (" + type + ")";
    }
}